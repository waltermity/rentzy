/** Hungarian text for an API error (code + backend message). */
export function translateError(code: string, message: string): string {
  for (const [re, fn] of patterns) {
    const m = message.match(re)
    if (m) return fn(m)
  }
  return byCode[code] ?? 'Hiba történt.'
}
